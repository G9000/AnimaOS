//! The read-only file copy of core memory: `USER.md` (About you) and
//! `MEMORY.md` (Agent notes) in the agent's profile directory, beside the
//! profile `SOUL.md`. The memory store stays the source of truth; agents may
//! not write these files (`agent_files::write_policy`), and they are not loaded
//! as agent files. A failed write is logged and never fails a memory change.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use anima_memory::{Memory, MemoryManager};
use tracing::warn;

use super::{blocks_for, entry_line, CoreBlock};
use crate::agent_files::selection::profile_relative;

pub(crate) const HEADER: &str =
    "Generated by AnimaOS from core memory. Edits here are overwritten; edit in the console.";

pub(crate) const fn file_name(block: CoreBlock) -> &'static str {
    match block {
        CoreBlock::User => "USER.md",
        CoreBlock::Notes => "MEMORY.md",
    }
}

/// The copy's text: the header line, then one `- entry` line per entry, as in
/// run context (flagged entries show only their scanner ids).
pub(crate) fn contents(entries: &[Memory]) -> String {
    let mut text = format!("{HEADER}\n");
    for memory in entries {
        text.push_str(&entry_line(memory));
    }
    text
}

/// Rewrites both copies for `agent_id` from the store. Call it under the
/// memory lock that committed the change, so two edits cannot land their
/// copies out of order. No workspace (or an empty root) skips the copy.
pub(crate) fn write_copies(workspace_root: Option<&Path>, manager: &MemoryManager, agent_id: &str) {
    let Some(root) = workspace_root.filter(|root| !root.as_os_str().is_empty()) else {
        return;
    };
    let (user, notes) = blocks_for(manager, agent_id);
    if let Err(error) = write_blocks(
        root,
        agent_id,
        &[(CoreBlock::User, &user), (CoreBlock::Notes, &notes)],
    ) {
        warn!(agent_id, %error, "could not write the core memory file copy");
    }
}

fn write_blocks(
    root: &Path,
    agent_id: &str,
    blocks: &[(CoreBlock, &Vec<Memory>)],
) -> io::Result<()> {
    let directory = root.join(profile_relative(agent_id));
    // An agent never gets a copy until it has an entry; an existing copy is
    // kept current, down to the header alone.
    if blocks.iter().all(|(_, entries)| entries.is_empty())
        && blocks
            .iter()
            .all(|(block, _)| fs::symlink_metadata(directory.join(file_name(*block))).is_err())
    {
        return Ok(());
    }
    // The workspace root must already exist; a missing root is never recreated.
    if !root.is_dir() {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            "the workspace root is not a directory",
        ));
    }
    // The profile directory sits under the workspace; never follow a link out.
    // Check the nearest existing ancestor before creating anything, so a
    // symlinked `.animaos-swarm` cannot make directories outside the workspace.
    let root_real = root.canonicalize()?;
    let ancestor = directory
        .ancestors()
        .find(|path| path.exists())
        .unwrap_or(root);
    if !ancestor.canonicalize()?.starts_with(&root_real) {
        return Err(outside_workspace());
    }
    fs::create_dir_all(&directory)?;
    if !directory.canonicalize()?.starts_with(&root_real) {
        return Err(outside_workspace());
    }
    for (block, entries) in blocks {
        replace_file(&directory, file_name(*block), &contents(entries))?;
    }
    Ok(())
}

fn outside_workspace() -> io::Error {
    io::Error::new(
        io::ErrorKind::PermissionDenied,
        "the profile directory resolves outside the workspace",
    )
}

/// Writes a temporary file beside the target and renames it into place.
fn replace_file(directory: &Path, name: &str, text: &str) -> io::Result<()> {
    let temporary: PathBuf = directory.join(format!(".{name}.{}.tmp", uuid::Uuid::new_v4()));
    if let Err(error) = fs::write(&temporary, text) {
        let _ = fs::remove_file(&temporary);
        return Err(error);
    }
    fs::rename(&temporary, directory.join(name)).inspect_err(|_| {
        let _ = fs::remove_file(&temporary);
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::core_memory::{apply_edit, CoreAgent, CoreEdit, ScanMode};

    const AGENT: CoreAgent<'static> = CoreAgent {
        id: "agent-files",
        name: "Anima",
    };

    fn temp_root(label: &str) -> PathBuf {
        let root =
            std::env::temp_dir().join(format!("anima-core-files-{label}-{}", uuid::Uuid::new_v4()));
        fs::create_dir_all(&root).unwrap();
        root
    }

    fn add(manager: &mut MemoryManager, block: CoreBlock, text: &str) {
        apply_edit(
            manager,
            AGENT,
            block,
            CoreEdit::Add { text: text.into() },
            ScanMode::Refuse,
        )
        .unwrap();
    }

    #[test]
    fn copies_hold_the_header_and_one_line_per_entry() {
        let root = temp_root("write");
        let mut manager = MemoryManager::new();
        add(&mut manager, CoreBlock::User, "prefers metric units");
        add(
            &mut manager,
            CoreBlock::User,
            "lives in   Lisbon\nand works remotely",
        );
        add(&mut manager, CoreBlock::Notes, "the build needs bun 1.2");

        write_copies(Some(&root), &manager, AGENT.id);

        let directory = root.join(profile_relative(AGENT.id));
        assert_eq!(
            fs::read_to_string(directory.join("USER.md")).unwrap(),
            format!("{HEADER}\n- prefers metric units\n- lives in Lisbon and works remotely\n")
        );
        assert_eq!(
            fs::read_to_string(directory.join("MEMORY.md")).unwrap(),
            format!("{HEADER}\n- the build needs bun 1.2\n")
        );
        assert_eq!(
            fs::read_dir(&directory).unwrap().count(),
            2,
            "no temporary file is left behind"
        );

        // Removing the last entry keeps the copy, down to the header.
        apply_edit(
            &mut manager,
            AGENT,
            CoreBlock::Notes,
            CoreEdit::Remove {
                old_text: "bun".into(),
            },
            ScanMode::Refuse,
        )
        .unwrap();
        write_copies(Some(&root), &manager, AGENT.id);
        assert_eq!(
            fs::read_to_string(directory.join("MEMORY.md")).unwrap(),
            format!("{HEADER}\n")
        );
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn no_copy_without_a_workspace_or_any_entry() {
        let root = temp_root("empty");
        let mut manager = MemoryManager::new();
        write_copies(Some(&root), &manager, AGENT.id);
        assert!(!root.join(".animaos-swarm").exists());

        add(&mut manager, CoreBlock::User, "prefers metric units");
        write_copies(None, &manager, AGENT.id);
        write_copies(Some(Path::new("")), &manager, AGENT.id);
        assert!(!root.join(".animaos-swarm").exists());
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn a_failing_directory_is_logged_and_never_panics() {
        let root = temp_root("blocked");
        // A file where the profile directory tree should start.
        fs::write(root.join(".animaos-swarm"), "not a directory").unwrap();
        let mut manager = MemoryManager::new();
        add(&mut manager, CoreBlock::User, "prefers metric units");
        write_copies(Some(&root), &manager, AGENT.id);
        assert_eq!(
            fs::read_to_string(root.join(".animaos-swarm")).unwrap(),
            "not a directory"
        );
        let _ = fs::remove_dir_all(root);
    }

    #[cfg(unix)]
    #[test]
    fn a_profile_directory_linked_out_of_the_workspace_is_not_written() {
        let root = temp_root("linked");
        let outside = temp_root("outside");
        let directory = root.join(profile_relative(AGENT.id));
        fs::create_dir_all(directory.parent().unwrap()).unwrap();
        std::os::unix::fs::symlink(&outside, &directory).unwrap();
        let mut manager = MemoryManager::new();
        add(&mut manager, CoreBlock::User, "prefers metric units");
        write_copies(Some(&root), &manager, AGENT.id);
        assert_eq!(fs::read_dir(&outside).unwrap().count(), 0);
        let _ = fs::remove_dir_all(root);
        let _ = fs::remove_dir_all(outside);
    }

    #[cfg(unix)]
    #[test]
    fn a_linked_agent_profiles_root_creates_no_directory_outside_the_workspace() {
        let root = temp_root("linked-root");
        let outside = temp_root("outside-root");
        std::os::unix::fs::symlink(&outside, root.join(".animaos-swarm")).unwrap();
        let mut manager = MemoryManager::new();
        add(&mut manager, CoreBlock::User, "prefers metric units");
        write_copies(Some(&root), &manager, AGENT.id);
        assert_eq!(
            fs::read_dir(&outside).unwrap().count(),
            0,
            "no directory was created through the link"
        );
        let _ = fs::remove_dir_all(root);
        let _ = fs::remove_dir_all(outside);
    }

    #[test]
    fn a_missing_workspace_root_is_not_recreated() {
        let root = temp_root("gone");
        fs::remove_dir_all(&root).unwrap();
        let mut manager = MemoryManager::new();
        add(&mut manager, CoreBlock::User, "prefers metric units");
        write_copies(Some(&root), &manager, AGENT.id);
        assert!(!root.exists());
    }
}
